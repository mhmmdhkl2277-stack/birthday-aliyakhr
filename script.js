// --- hati melayang + confetti (canvas)
const cv = $('#fx'), cx = cv.getContext('2d'); let W, H, parts = [];
const resize = () => { W = cv.width = innerWidth; H = cv.height = innerHeight; }; resize(); addEventListener('resize', resize);
const spawn = (burst) => ({
  x: burst ? W / 2 : Math.random() * W, y: burst ? H * .6 : H + 20,
  s: 8 + Math.random() * 14, vx: burst ? (Math.random() - .5) * 10 : (Math.random() - .5) * .4,
  vy: burst ? -Math.random() * 9 - 3 : -(.3 + Math.random() * .7), a: .15 + Math.random() * .35,
  g: burst ? .15 : 0, h: ['♥', '✦', '♡'][Math.floor(Math.random() * 3)], c: burst ? ['#ff2e93', '#f5c26b', '#ff7eb6'][Math.floor(Math.random() * 3)] : '#ff7eb6', life: burst ? 160 : Infinity
});
function confetti() { for (let i = 0; i < 90; i++) parts.push(spawn(true)); }
for (let i = 0; i < 25; i++) { const p = spawn(); p.y = Math.random() * H; parts.push(p); }
(function loop() {
  cx.clearRect(0, 0, W, H);
  parts.forEach(p => {
    p.x += p.vx; p.y += p.vy; p.vy += p.g; p.life--;
    cx.globalAlpha = p.life < 40 ? p.a * p.life / 40 : p.a; cx.fillStyle = p.c; cx.font = p.s + 'px serif'; cx.fillText(p.h, p.x, p.y);
    if (p.life === Infinity && p.y < -20) Object.assign(p, spawn());
  });
  parts = parts.filter(p => p.life > 0);
  if (parts.filter(p => p.life === Infinity).length < 25 && Math.random() < .03) parts.push(spawn());
  requestAnimationFrame(loop);
})();
