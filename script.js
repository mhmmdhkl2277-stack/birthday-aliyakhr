// primeAudio: dipanggil saat klik/Enter. Memutar audio sepersekian detik lalu menjeda,
// supaya browser (terutama Safari iPhone) mengizinkan musik dimulai nanti tanpa klik lagi.
function primeAudio() {
  audio.muted = true;
  audio.play().then(() => { audio.pause(); audio.currentTime = 0; audio.muted = false; })
              .catch(() => { audio.muted = false; });
}
// playMusic: kalau browser tetap menolak, musik mulai di sentuhan/klik pertama berikutnya
function playMusic() {
  audio.muted = false;
  audio.play().catch(() => {
    document.addEventListener('pointerdown', () => audio.play().catch(() => {}), { once: true });
  });
}
