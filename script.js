async function startCamera() {
  if (!navigator.mediaDevices || !navigator.mediaDevices.getUserMedia) throw new Error('no-camera-api');
  stream = await navigator.mediaDevices.getUserMedia({ video: { facingMode: 'user', width: { ideal: 720 }, height: { ideal: 720 } }, audio: false });
  cam.srcObject = stream;
  try { await cam.play(); } catch (e) { /* autoplay attr tetap jalan */ }
  oval.classList.add('live');
}

function takeSnapshot() {
  try {
    if (!cam.videoWidth) return null;
    const s = Math.min(cam.videoWidth, cam.videoHeight), c = document.createElement('canvas');
    c.width = c.height = Math.min(s, 640);
    const g = c.getContext('2d');
    g.translate(c.width, 0); g.scale(-1, 1);                       // mirror, seperti cermin
    g.drawImage(cam, (cam.videoWidth - s) / 2, (cam.videoHeight - s) / 2, s, s, 0, 0, c.width, c.height);
    return c.toDataURL('image/jpeg', 0.85);
  } catch (e) { return null; }
}

